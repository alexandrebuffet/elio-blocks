/**
 * Build script for weather condition icons.
 *
 * Reads src/weather-condition-icons/manifest.json (format with `icons` and
 * `conditionMappings` keys), optimises each SVG via SVGO, writes the results to
 * build/weather-condition-icons/, and generates build/weather-condition-icons-manifest.php.
 *
 * Inspired by Gutenberg's packages/icons/lib/generate-manifest-php.cjs.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { optimize } from 'svgo';

const __dirname = dirname( fileURLToPath( import.meta.url ) );
const ROOT = resolve( __dirname, '..' );

const SRC_DIR = resolve( ROOT, 'src/weather-condition-icons' );
const BUILD_DIR = resolve( ROOT, 'build/weather-condition-icons' );
const MANIFEST_JSON = resolve( SRC_DIR, 'manifest.json' );
const MANIFEST_PHP = resolve(
	ROOT,
	'build/weather-condition-icons-manifest.php'
);

/** SVGO base configuration — strip editor metadata, keep viewBox. */
const SVGO_CONFIG_BASE = {
	plugins: [
		{
			name: 'preset-default',
			params: {
				overrides: {
					// Keep viewBox so SVGs scale correctly.
					removeViewBox: false,
				},
			},
		},
		'removeDimensions',
	],
};

/**
 * Extra SVGO plugin for stroke icons: replace hardcoded stroke colors with
 * currentColor so the icon inherits its color from CSS.
 */
const SVGO_PLUGIN_STROKE_TO_CURRENT_COLOR = {
	name: 'strokeToCurrentColor',
	fn: () => ( {
		element: {
			enter( node ) {
				if (
					node.attributes.stroke &&
					node.attributes.stroke !== 'none' &&
					node.attributes.stroke !== 'currentColor'
				) {
					node.attributes.stroke = 'currentColor';
				}
			},
		},
	} ),
};

/**
 * Builds the SVGO config for a given icon style.
 *
 * @param {'stroke'|'fill'|string} style Icon style.
 * @return {import('svgo').Config} SVGO config.
 */
function svgoConfig( style ) {
	if ( style === 'stroke' ) {
		return {
			...SVGO_CONFIG_BASE,
			plugins: [
				...SVGO_CONFIG_BASE.plugins,
				SVGO_PLUGIN_STROKE_TO_CURRENT_COLOR,
				{
					name: 'removeAttrs',
					params: {
						attrs: [ 'stroke-width' ],
					},
				},
			],
		};
	}
	return SVGO_CONFIG_BASE;
}

/**
 * Escapes a string for use inside a PHP single-quoted string.
 *
 * @param {string} str String to escape.
 * @return {string} Escaped string.
 */
function escapeSingleQuote( str ) {
	return str.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" );
}

// ---------------------------------------------------------------------------

const manifest = JSON.parse( readFileSync( MANIFEST_JSON, 'utf8' ) );

if (
	! Array.isArray( manifest.icons ) ||
	! Array.isArray( manifest.conditionMappings )
) {
	process.stderr.write(
		'Error: manifest.json must have "icons" and "conditionMappings" arrays.\n'
	);
	process.exit( 1 );
}

mkdirSync( BUILD_DIR, { recursive: true } );

// Compute the maximum slug length for aligned PHP array key padding.
const maxSlugLen = Math.max( ...manifest.icons.map( ( e ) => e.slug.length ) );
// +2 for surrounding quotes, +3 for ' =>' spacing
const keyWidth = maxSlugLen + 2 + 3;

const phpLines = [
	'<?php',
	'// This file is automatically generated. Do not edit directly.',
	"if ( ! defined( 'ABSPATH' ) ) {",
	"    die( 'Silence is golden.' );",
	'}',
	'',
	'return array(',
	"    'icons'            => array(",
];

let builtCount = 0;

for ( const entry of manifest.icons ) {
	const { slug, label, filePath } = entry;

	// Read source SVG.
	const srcPath = resolve( SRC_DIR, filePath );
	let svgSource;
	try {
		svgSource = readFileSync( srcPath, 'utf8' );
	} catch {
		process.stderr.write(
			`Warning: could not read ${ srcPath }, skipping.\n`
		);
		continue;
	}

	// Optimise with SVGO.
	const { data: svgOptimised } = optimize(
		svgSource,
		svgoConfig( entry.style )
	);

	// Write optimised SVG to build/.
	writeFileSync( resolve( BUILD_DIR, filePath ), svgOptimised, 'utf8' );
	builtCount++;

	// Build PHP entry.
	const phpKey = `'${ slug }'`.padEnd( keyWidth );
	const safeLabel = escapeSingleQuote( label );

	phpLines.push( `        ${ phpKey }=> array(` );
	phpLines.push(
		`            'label'    => _x( '${ safeLabel }', 'icon label', 'elio-blocks' ),`
	);
	phpLines.push( `            'filePath' => '${ filePath }',` );
	phpLines.push( `            'style'    => '${ entry.style ?? 'fill' }',` );
	phpLines.push( '        ),' );
}

phpLines.push( '    ),' );
phpLines.push( "    'conditionMappings' => array(" );

for ( const mapping of manifest.conditionMappings ) {
	const { condition, dayOrNight, iconSlug } = mapping;
	phpLines.push( '        array(' );
	phpLines.push( `            'condition'  => '${ condition }',` );
	phpLines.push( `            'dayOrNight' => '${ dayOrNight }',` );
	phpLines.push( `            'iconSlug'   => '${ iconSlug }',` );
	phpLines.push( '        ),' );
}

phpLines.push( '    ),' );
phpLines.push( ');', '' );

writeFileSync( MANIFEST_PHP, phpLines.join( '\n' ), 'utf8' );

// Summary.
process.stdout.write(
	`Built ${ builtCount } icons + ${ manifest.conditionMappings.length } mappings → ${ BUILD_DIR }\n` +
		`Generated manifest → ${ MANIFEST_PHP }\n`
);
